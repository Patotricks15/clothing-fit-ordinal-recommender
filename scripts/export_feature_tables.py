"""Export the feature catalogue from conf/features.yaml as a LaTeX table.

The paper describes the features; this keeps that description generated
from the same YAML the pipeline executes, so a feature cannot be removed
from the code while surviving in the write-up.
"""

from __future__ import annotations

import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT / "src"))

from recommender.features.spec import default_spec_path, load_feature_specs  # noqa: E402

STATIC_NAMES = {
    "user_height_cm", "user_weight_kg", "user_bmi", "user_bust_band",
    "user_bust_cup_ordinal", "user_body_type", "user_age", "item_category",
    "item_nominal_size", "context_rented_for",
}


def escape(text: str) -> str:
    """Escape the LaTeX special characters that appear in our metadata."""
    for char in ("\\", "&", "%", "$", "#", "_", "{", "}"):
        text = text.replace(char, "\\" + char)
    return text


def to_latex(specs) -> str:  # noqa: ANN001
    lines = [
        "% Generated by scripts/export_feature_tables.py -- do not edit by hand.",
        r"\begin{table}[t]",
        r"  \centering",
        r"  \caption{Engineered features. Static attributes need no cut-off;",
        r"  historical aggregates are computed strictly before the row being",
        r"  predicted (point-in-time).}",
        r"  \label{tab:features}",
        r"  \begin{tabular}{llll}",
        r"    \toprule",
        r"    Feature & Family & Type & Point-in-time \\",
        r"    \midrule",
    ]
    for spec in specs:
        feature_type = "static" if spec.name in STATIC_NAMES else "historical aggregate"
        lines.append(
            "    "
            + " & ".join(
                [
                    rf"\texttt{{{escape(spec.name)}}}",
                    escape(spec.family),
                    feature_type,
                    r"\checkmark" if spec.point_in_time else "--",
                ]
            )
            + r" \\"
        )
    lines += [r"    \bottomrule", r"  \end{tabular}", r"\end{table}", ""]
    return "\n".join(lines)


def to_rationale_latex(specs) -> str:  # noqa: ANN001
    lines = [
        "% Generated by scripts/export_feature_tables.py -- do not edit by hand.",
        r"\begin{description}",
    ]
    for spec in specs:
        lines.append(
            rf"  \item[\texttt{{{escape(spec.name)}}}] {escape(spec.rationale.strip())}"
        )
    lines += [r"\end{description}", ""]
    return "\n".join(lines)


def main() -> int:
    specs = load_feature_specs(default_spec_path())

    tables = PROJECT_ROOT / "paper" / "tables"
    tables.mkdir(parents=True, exist_ok=True)
    (tables / "features.tex").write_text(to_latex(specs))
    (tables / "feature-rationale.tex").write_text(to_rationale_latex(specs))

    print(f"wrote {tables / 'features.tex'} ({len(specs)} features)")
    print(f"wrote {tables / 'feature-rationale.tex'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
