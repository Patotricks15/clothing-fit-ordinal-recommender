"""Export the evaluation results as a LaTeX table and a Markdown table.

Having one generator feed both ``paper/tables/results.tex`` and the README
block is what stops the two surfaces from drifting apart as the model
changes.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT / "src"))

from recommender.cli import _build_models, _design_matrices, _load_split  # noqa: E402
from recommender.evaluation import evaluate_classification, evaluate_conformal  # noqa: E402
from recommender.models import SplitConformalClassifier, Standardizer  # noqa: E402

CLASS_COLUMNS = ["model", "accuracy", "mae_ordinal", "accuracy_within_1", "macro_f1"]
CONFORMAL_COLUMNS = ["model", "target_coverage", "empirical_coverage", "average_set_size"]
HEADERS = {
    "model": "Model",
    "accuracy": "Accuracy",
    "mae_ordinal": "MAE (ordinal)",
    "accuracy_within_1": "Acc. within 1",
    "macro_f1": "Macro F1",
    "target_coverage": "Target cov.",
    "empirical_coverage": "Empirical cov.",
    "average_set_size": "Avg. set size",
}
CONFORMAL_ALPHA = 0.1


def compute_results(
    data_path: Path, seed: int
) -> tuple[pd.DataFrame, pd.DataFrame]:
    _, split, feature_store = _load_split(data_path, seed)
    (train_X, train_y), (val_X, val_y), (test_X, test_y) = _design_matrices(feature_store, split)

    scaler = Standardizer().fit(train_X)
    train_Xs, val_Xs, test_Xs = (
        scaler.transform(train_X), scaler.transform(val_X), scaler.transform(test_X)
    )

    class_rows, conformal_rows = [], []
    for name, model in _build_models(seed).items():
        model.fit(train_Xs, train_y)
        preds = model.predict(test_Xs)
        class_rows.append(
            evaluate_classification(test_y, preds, n_classes=3, model_name=name).as_row()
        )

        if hasattr(model, "predict_proba"):
            conformal = SplitConformalClassifier(alpha=CONFORMAL_ALPHA)
            conformal.calibrate(model.predict_proba(val_Xs), val_y)
            conformal_rows.append(
                evaluate_conformal(
                    conformal, model.predict_proba(test_Xs), test_y, model_name=name
                ).as_row()
            )

    class_frame = pd.DataFrame(class_rows)[CLASS_COLUMNS].sort_values(
        "mae_ordinal", ascending=True
    )
    conformal_frame = pd.DataFrame(conformal_rows)[CONFORMAL_COLUMNS]
    return class_frame, conformal_frame


def _to_latex(frame: pd.DataFrame, columns: list[str], caption: str, label: str) -> str:
    best = frame["mae_ordinal"].min() if "mae_ordinal" in columns else None
    lines = [
        "% Generated by scripts/export_results_table.py -- do not edit by hand.",
        r"\begin{table}[t]",
        r"  \centering",
        rf"  \caption{{{caption}}}",
        rf"  \label{{{label}}}",
        r"  \begin{tabular}{l" + "r" * (len(columns) - 1) + "}",
        r"    \toprule",
        "    " + " & ".join(HEADERS[c] for c in columns) + r" \\",
        r"    \midrule",
    ]
    for _, row in frame.iterrows():
        cells = [str(row["model"]).replace("_", r"\_")]
        for col in columns[1:]:
            value = f"{row[col]:.4f}"
            if best is not None and col == "mae_ordinal" and row[col] == best:
                value = rf"\textbf{{{value}}}"
            cells.append(value)
        lines.append("    " + " & ".join(cells) + r" \\")
    lines += [r"    \bottomrule", r"  \end{tabular}", r"\end{table}", ""]
    return "\n".join(lines)


def to_markdown(frame: pd.DataFrame, columns: list[str]) -> str:
    header = "| " + " | ".join(HEADERS[c] for c in columns) + " |"
    sep = "|" + "|".join(["---"] * len(columns)) + "|"
    rows = [
        "| " + " | ".join(
            [str(r["model"])] + [f"{r[c]:.4f}" for c in columns[1:]]
        ) + " |"
        for _, r in frame.iterrows()
    ]
    return "\n".join([header, sep, *rows])


def main() -> int:
    data_path = PROJECT_ROOT / "data" / "fit_records.csv"
    if not data_path.exists():
        raise SystemExit(f"{data_path} not found. Run scripts/download_data.py --synthetic")

    class_frame, conformal_frame = compute_results(data_path, seed=42)

    tables = PROJECT_ROOT / "paper" / "tables"
    tables.mkdir(parents=True, exist_ok=True)
    (tables / "results.tex").write_text(
        _to_latex(
            class_frame, CLASS_COLUMNS,
            "Point-prediction quality on the held-out test partition. "
            "Hyperparameters for every model were selected on the validation "
            "partition; the test partition was read once.",
            "tab:results",
        )
    )
    (tables / "conformal-results.tex").write_text(
        _to_latex(
            conformal_frame, CONFORMAL_COLUMNS,
            r"Split conformal calibration at target coverage $1-\alpha=0.9$, "
            "calibrated on the validation partition and evaluated on test.",
            "tab:conformal",
        )
    )

    artifacts = PROJECT_ROOT / "artifacts"
    artifacts.mkdir(exist_ok=True)
    class_frame.to_csv(artifacts / "results.csv", index=False)
    conformal_frame.to_csv(artifacts / "conformal_results.csv", index=False)
    (artifacts / "results.md").write_text(to_markdown(class_frame, CLASS_COLUMNS) + "\n")

    print(to_markdown(class_frame, CLASS_COLUMNS))
    print()
    print(to_markdown(conformal_frame, CONFORMAL_COLUMNS))
    print(f"\nwrote {tables / 'results.tex'}")
    print(f"wrote {tables / 'conformal-results.tex'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
